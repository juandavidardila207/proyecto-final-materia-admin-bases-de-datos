#!/bin/bash
# DEMO error humano: borra las matrículas de un curso y las recupera con FLASHBACK TABLE.
set -euo pipefail
source "$(dirname "$0")/_comun.sh"
sql_pdb <<'SQL'
SET FEEDBACK OFF HEADING ON
WHENEVER SQLERROR EXIT SQL.SQLCODE
COLUMN scn_antes NEW_VALUE scn_antes
SELECT TIMESTAMP_TO_SCN(SYSTIMESTAMP) AS scn_antes FROM dual;
EXEC DBMS_SESSION.SLEEP(4)
SELECT COUNT(*) AS "ANTES" FROM UNIVERSIDAD.MATRICULAS;
DELETE FROM UNIVERSIDAD.MATRICULAS WHERE id_curso = 101;
COMMIT;
SELECT COUNT(*) AS "TRAS_EL_BORRADO" FROM UNIVERSIDAD.MATRICULAS;
FLASHBACK TABLE UNIVERSIDAD.MATRICULAS TO SCN &scn_antes;
SELECT COUNT(*) AS "TRAS_FLASHBACK" FROM UNIVERSIDAD.MATRICULAS;
EXIT
SQL
