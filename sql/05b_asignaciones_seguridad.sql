-- Permisos y bitácora de ASIGNACIONES (lo usan 05_seguridad.sql y 08_migracion_asignaciones.sql)
GRANT SELECT ON UNIVERSIDAD.ASIGNACIONES TO ROL_UNIV_CONSULTA;
GRANT INSERT, DELETE ON UNIVERSIDAD.ASIGNACIONES TO ROL_UNIV_OPERADOR;

CREATE OR REPLACE TRIGGER UNIVERSIDAD.TRG_AUD_ASIGNACIONES
AFTER INSERT OR DELETE ON UNIVERSIDAD.ASIGNACIONES FOR EACH ROW
BEGIN
  UNIV_SEC.REGISTRAR_CAMBIO(
    CASE WHEN INSERTING THEN 'INSERT' ELSE 'DELETE' END, 'ASIGNACIONES',
    COALESCE(:NEW.id_profesor, :OLD.id_profesor),
    CASE WHEN DELETING THEN JSON_OBJECT('id_curso' VALUE :OLD.id_curso, 'id_profesor' VALUE :OLD.id_profesor) END,
    CASE WHEN INSERTING THEN JSON_OBJECT('id_curso' VALUE :NEW.id_curso, 'id_profesor' VALUE :NEW.id_profesor) END);
END;
/
