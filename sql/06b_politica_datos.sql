-- Política de auditoría sobre las tablas del taller.
-- Va en un archivo aparte porque hay que volver a crearla después de un impdp con
-- TABLE_EXISTS_ACTION=REPLACE: al recrearse las tablas, la política queda activa pero VACÍA.
-- La vuelve a ejecutar backup/04_import_datapump.sh.
BEGIN
  EXECUTE IMMEDIATE 'NOAUDIT POLICY POL_UNIV_DATOS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
BEGIN
  EXECUTE IMMEDIATE 'DROP AUDIT POLICY POL_UNIV_DATOS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
CREATE AUDIT POLICY POL_UNIV_DATOS
  ACTIONS INSERT ON UNIVERSIDAD.PROFESORES, UPDATE ON UNIVERSIDAD.PROFESORES, DELETE ON UNIVERSIDAD.PROFESORES,
          INSERT ON UNIVERSIDAD.CURSOS,     UPDATE ON UNIVERSIDAD.CURSOS,     DELETE ON UNIVERSIDAD.CURSOS,
          INSERT ON UNIVERSIDAD.MATRICULAS, UPDATE ON UNIVERSIDAD.MATRICULAS, DELETE ON UNIVERSIDAD.MATRICULAS,
          INSERT ON UNIVERSIDAD.ESTUDIANTES, UPDATE ON UNIVERSIDAD.ESTUDIANTES, DELETE ON UNIVERSIDAD.ESTUDIANTES,
          INSERT ON UNIVERSIDAD.ASIGNACIONES, DELETE ON UNIVERSIDAD.ASIGNACIONES;
AUDIT POLICY POL_UNIV_DATOS;
